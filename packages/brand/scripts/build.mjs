import StyleDictionary from 'style-dictionary'

const HEADER = 'Generated by packages/brand/scripts/build.mjs from tokens/. Do not edit.'

// `DEFAULT` marks the unsuffixed token of a group (`--radius` next to `--radius-sm`).
const pathOf = (token) => token.path.filter((part) => part !== 'DEFAULT')

const GENERIC_FAMILIES = new Set(['serif', 'sans-serif', 'monospace'])

const quote = (name) => (GENERIC_FAMILIES.has(name) ? name : `"${name}"`)

const cssValue = (token) =>
  token.$type === 'fontFamily' ? token.$value.map(quote).join(', ') : token.$value

const jsValue = (token) => (token.$type === 'fontFamily' ? cssValue(token) : token.$value)

const group = (tokens) => {
  const tree = {}
  for (const token of tokens) {
    const [name, ...rest] = token.path
    tree[name] ??= {}
    tree[name][rest.join('-') || 'DEFAULT'] = jsValue(token)
  }
  return tree
}

StyleDictionary.registerFormat({
  name: 'brand/theme-css',
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens.map(
      (token) => `  --${pathOf(token).join('-')}: ${cssValue(token)};`,
    )
    return `/* ${HEADER} */\n@theme {\n${lines.join('\n')}\n}\n`
  },
})

StyleDictionary.registerFormat({
  name: 'brand/tokens-js',
  format: ({ dictionary }) => {
    const tree = group(dictionary.allTokens)
    const exports = Object.entries(tree).map(
      ([name, values]) => `export const ${name} = ${JSON.stringify(values, null, 2)}\n`,
    )
    return `// ${HEADER}\n${exports.join('\n')}`
  },
})

StyleDictionary.registerFormat({
  name: 'brand/tokens-dts',
  format: ({ dictionary }) => {
    const tree = group(dictionary.allTokens)
    const exports = Object.entries(tree).map(([name, values]) => {
      const fields = Object.entries(values).map(
        ([key, value]) => `  readonly ${JSON.stringify(key)}: ${JSON.stringify(value)}`,
      )
      return `export declare const ${name}: {\n${fields.join('\n')}\n}\n`
    })
    return `// ${HEADER}\n${exports.join('\n')}`
  },
})

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  platforms: {
    dist: {
      transforms: ['name/kebab'],
      buildPath: 'dist/',
      files: [
        { destination: 'theme.css', format: 'brand/theme-css' },
        { destination: 'tokens.js', format: 'brand/tokens-js' },
        { destination: 'tokens.d.ts', format: 'brand/tokens-dts' },
      ],
    },
  },
})

await sd.buildAllPlatforms()
